from __future__ import annotations

from typing import Any

from .constants import UNAVAILABLE_OPERATORS

CONVERSIONS = {
    "number": "Number",
    "text": "Text",
    "boolean": "Boolean",
    "timespan_ms": "TimespanMs",
}

NEW_DATA_SEGMENT = ".GameData.NewData."


def literal(value: str | None) -> str:
    if value is None:
        return "null"
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def pascal(name: str) -> str:
    return "".join(part.capitalize() for part in name.split("_"))


def comparisons() -> list[str]:
    return ["None", *(pascal(operator) for operator in UNAVAILABLE_OPERATORS)]


def property_fallback(name: str) -> str | None:
    if NEW_DATA_SEGMENT not in name:
        return None
    return name.replace(NEW_DATA_SEGMENT, ".GameData.", 1)


def computations(mappings: dict[str, dict[str, Any]]) -> list[str]:
    names = {
        mapping["computed"] for mapping in mappings.values() if "computed" in mapping
    }
    return ["None", *sorted(names)]


def csharp_value(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return literal(value)
    return f"{float(value)!r}"


def game_source(game: str, source: dict[str, Any]) -> str:
    values = source.get("values")
    pairs = (
        "null"
        if values is None
        else "new object[] { "
        + ", ".join(f"{literal(key)}, {csharp_value(value)}" for key, value in values.items())
        + " }"
    )
    parts = [
        literal(game),
        literal(source["property"]),
        repr(float(source.get("scale", 1))),
        pairs,
        csharp_value(source["default"]) if "default" in source else "null",
        str(source.get("bit", -1)),
        "true" if source.get("clock") else "false",
    ]
    return f"new GameSource({', '.join(parts)})"


def game_sources(mapping: dict[str, Any], games: dict[str, Any]) -> str:
    sources = [
        game_source(games[game_id]["simhub"], source)
        for game_id, source in mapping.get("games", {}).items()
        if isinstance(source, dict)
    ]
    return "null" if not sources else "new[] { " + ", ".join(sources) + " }"


def entry(field: dict[str, str], mapping: dict[str, Any], games: dict[str, Any]) -> str:
    name = mapping.get("property")
    computed = mapping.get("computed")
    rule = mapping.get("unavailable_when")
    parts = [
        literal(field["wire_id"]),
        literal(field["name"]),
        literal(name),
        literal(None if name is None else property_fallback(name)),
        f"FieldComputation.{computed or 'None'}",
        f"FieldConversion.{CONVERSIONS[mapping.get('conversion', 'number')]}",
        literal(mapping.get("format")),
        repr(float(mapping.get("scale", 1))),
        literal(mapping.get("fallback")),
        f"FieldComparison.{pascal(rule['op']) if rule else 'None'}",
        repr(float(rule["value"] if rule else 0)),
        f"FieldRate.{field['rate'].capitalize()}",
        game_sources(mapping, games),
    ]
    return f"            new TelemetryField({', '.join(parts)}),"


