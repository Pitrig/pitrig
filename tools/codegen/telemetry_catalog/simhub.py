from __future__ import annotations

import json
from typing import Any


def identifier_key(identifier: str) -> int:
    first = ord(identifier[0])
    second = ord(identifier[1]) if len(identifier) == 2 else 0
    return (first << 8) | second


def generate_simhub(_document: dict[str, Any], fields: list[dict[str, str]]) -> str:
    descriptors = "\n".join(
        f'    {{"{field["wire_id"]}", "{field["name"]}"}},' for field in fields
    )
    lookup = sorted(
        (
            identifier_key(field["wire_id"]),
            index,
        )
        for index, field in enumerate(fields)
    )
    lookup_entries = "\n".join(
        f"    {{{key}, {index}}}," for key, index in lookup
    )
    return f"""// Generated by tools/codegen/telemetry_catalog. Do not edit.
#pragma once

#include <array>
#include <cstddef>
#include <cstdint>
#include <string_view>

namespace pitrig::protocols::simhub_catalog {{

struct BindingDescriptor {{
  std::string_view identifier;
  std::string_view canonical_name;
}};

struct LookupEntry {{
  std::uint16_t key;
  std::uint16_t binding_index;
}};

inline constexpr std::array<BindingDescriptor, {len(fields)}> kBindings{{{{
{descriptors}
}}}};

inline constexpr std::array<LookupEntry, {len(fields)}> kLookup{{{{
{lookup_entries}
}}}};

}}
"""


def primary_property(mapping: dict[str, Any]) -> str | None:
    if "property" in mapping:
        return mapping["property"]
    for source in mapping.get("games", {}).values():
        if isinstance(source, dict):
            return source["property"]
    return None


def generate_simhub_typescript(
    profile: dict[str, Any],
    fields: list[dict[str, str]],
    mappings: dict[str, dict[str, Any]],
) -> str:
    link = {
        "magic": profile["link"]["magic"],
        "version": profile["link"]["version"],
        "port": profile["link"]["port"],
        "sourcePort": profile["link"]["source_port"],
        "maximumPayload": profile["link"]["maximum_payload"],
        "keyframeIntervalMs": profile["link"]["keyframe_interval_ms"],
    }
    properties = [
        (field["name"], primary_property(mappings[field["name"]])) for field in fields
    ]
    entries = ",\n".join(
        f"  {json.dumps(name)}: {json.dumps(source, ensure_ascii=False)}"
        for name, source in properties
        if source is not None
    )
    link_json = json.dumps(link, ensure_ascii=False, separators=(",", ":"))
    return f"""// Generated by tools/codegen/telemetry_catalog. Do not edit.

export const SIMHUB_BAUD_RATE = {profile["baud_rate"]}

export const SIMHUB_LINK = {link_json} as const

export const SIMHUB_PROPERTIES: Readonly<Record<string, string>> = {{
{entries}
}}
"""
