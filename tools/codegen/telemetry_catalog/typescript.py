from __future__ import annotations

import json
from typing import Any

from .constants import CATEGORY_LABELS
from .game_sources import tracked_games


def generate_typescript(
    _document: dict[str, Any],
    fields: list[dict[str, str]],
    mappings: dict[str, dict[str, Any]],
    games: dict[str, Any],
) -> str:
    records = []
    for field in fields:
        record = {
            "name": field["name"],
            "wireId": field["wire_id"],
            "type": field["type"],
            "unit": field["unit"],
            "category": field["category"],
            "categoryLabel": CATEGORY_LABELS[field["category"]],
            "rate": field["rate"],
            "availability": field["availability"],
            "description": field["description"],
        }
        sent_by = tracked_games(mappings[field["name"]])
        if sent_by is not None:
            record["games"] = sent_by
        records.append("  " + json.dumps(record, ensure_ascii=False, separators=(",", ":")))
    body = ",\n".join(records)
    game_ids = " | ".join(f"'{game_id}'" for game_id in games)
    game_labels = json.dumps(
        {game_id: game["label"] for game_id, game in games.items()},
        ensure_ascii=False,
        separators=(",", ":"),
    )
    return f"""// Generated by tools/codegen/telemetry_catalog. Do not edit.

export type TelemetryValueType = 'text' | 'uint32' | 'int32' | 'float32' | 'boolean'
export type TelemetryRate = 'fast' | 'normal' | 'slow' | 'changes'
export type TelemetryAvailability = 'common' | 'optional' | 'computed' | 'game_specific'
export type TelemetryGame = {game_ids}

export const TELEMETRY_GAMES: Readonly<Record<TelemetryGame, string>> = {game_labels}

export interface TelemetryCatalogEntry {{
  name: string
  wireId: string
  type: TelemetryValueType
  unit: string
  category: string
  categoryLabel: string
  rate: TelemetryRate
  availability: TelemetryAvailability
  description: string
  games?: readonly TelemetryGame[]
}}

export const TELEMETRY_CATALOG = [
{body}
] as const satisfies readonly TelemetryCatalogEntry[]
"""
