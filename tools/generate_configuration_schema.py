def fail(message: str) -> None:
    print(f"configuration schema error: {message}", file=sys.stderr)
    raise SystemExit(1)


def load_schema() -> dict[str, Any]:
    if not SOURCE.exists():
        fail(f"missing source document {SOURCE.relative_to(ROOT)}")
    try:
        document = json.loads(SOURCE.read_text(encoding="utf-8"))
    except json.JSONDecodeError as error:
        fail(f"{SOURCE.relative_to(ROOT)} is not valid JSON: {error}")
    validate_schema(document)
    return document


def validate_schema(document: dict[str, Any]) -> None:
    for key in ("schema_version", "limits", "enums", "structs", "validation_errors"):
        if key not in document:
            fail(f"missing top-level key '{key}'")
    if not isinstance(document["schema_version"], int):
        fail("schema_version must be an integer")

    limits = document["limits"]
    structs = document["structs"]
    enums = document["enums"]
    externals = document.get("external_types", {})
    constants = document.get("constants", {})

    roots = [name for name, body in structs.items() if body.get("root")]
    if len(roots) != 1:
        fail(f"exactly one struct must be marked root, found {len(roots)}")

    known_scalars = set(SCALAR_CPP) | {"text"}
    for struct_name, body in structs.items():
        seen: set[str] = set()
        for field in body.get("fields", []):
            name = field.get("name")
            if not name:
                fail(f"{struct_name}: field without a name")
            if name in seen:
                fail(f"{struct_name}: duplicate field '{name}'")
            seen.add(name)
            kind = field.get("kind")
            if kind in known_scalars:
                continue
            if kind == "enum":
                if field.get("enum") not in enums:
                    fail(f"{struct_name}.{name}: unknown enum '{field.get('enum')}'")
            elif kind == "struct":
                if field.get("struct") not in structs:
                    fail(f"{struct_name}.{name}: unknown struct '{field.get('struct')}'")
            elif kind == "array":
                if field.get("struct") not in structs:
                    fail(f"{struct_name}.{name}: unknown struct '{field.get('struct')}'")
                if field.get("capacity") not in limits:
                    fail(f"{struct_name}.{name}: unknown capacity '{field.get('capacity')}'")
                if field.get("count_field") not in seen | {
                    other.get("name") for other in body.get("fields", [])
                }:
                    fail(f"{struct_name}.{name}: unknown count_field")
            elif kind == "external":
                if field.get("external") not in externals:
                    fail(f"{struct_name}.{name}: unknown external '{field.get('external')}'")
            else:
                fail(f"{struct_name}.{name}: unknown kind '{kind}'")
            if kind == "text" and field.get("capacity") not in limits:
                fail(f"{struct_name}.{name}: unknown capacity '{field.get('capacity')}'")

    for name, body in enums.items():
        values = body.get("json_values")
        if not values:
            fail(f"enum {name} has no values")
        if body.get("default") not in values:
            fail(f"enum {name}: default '{body.get('default')}' is not one of its values")

    for name, body in constants.items():
        if "value" not in body:
            fail(f"constant {name} has no value")


def root_struct(document: dict[str, Any]) -> str:
    return next(name for name, body in document["structs"].items() if body.get("root"))


def struct_order(document: dict[str, Any]) -> list[str]:
    """Dependency-first ordering so C++ definitions compile without forward declarations."""
    structs = document["structs"]
    ordered: list[str] = []
    visiting: set[str] = set()

    def visit(name: str) -> None:
        if name in ordered:
            return
        if name in visiting:
            fail(f"cyclic struct reference involving '{name}'")
        visiting.add(name)
        for field in structs[name].get("fields", []):
            if field["kind"] in ("struct", "array"):
                visit(field["struct"])
        visiting.discard(name)
        ordered.append(name)

    for name in structs:
        visit(name)
    return ordered


def serialized_fields(body: dict[str, Any]) -> list[dict[str, Any]]:
    return [field for field in body.get("fields", []) if field.get("serialized", True)]


def json_key(field: dict[str, Any]) -> str:
    return field.get("json", field["name"])


def object_keys(document: dict[str, Any], struct_name: str) -> list[str]:
    """Public JSON property names accepted inside one object, in declaration order."""
    body = document["structs"][struct_name]
    if body.get("serialized") is False:
        return []
    externals = document.get("external_types", {})
    # A widget variant carries the discriminator that selected it.
    keys: list[str] = ["type"] if body.get("widget_type") else []
    for field in serialized_fields(body):
        if field.get("flatten"):
            keys.extend(object_keys(document, field["struct"]))
        elif field["kind"] == "external" and field.get("inline"):
            # The external contributes its own keys inline; its C++ member name
            # is not a public property.
            keys.extend(externals[field["external"]]["keys"])
        else:
            keys.append(json_key(field))
    return keys


def text_fields(
    document: dict[str, Any], body: dict[str, Any]
) -> list[tuple[str, dict[str, Any]]]:
    """Bounded strings a validator sees at this level, following flattened structs.

    A flattened struct contributes its properties here, so its capacities have to
    be reported under this name too or a check would look them up and miss.
    """
    found: list[tuple[str, dict[str, Any]]] = []
    for field in serialized_fields(body):
        if field.get("flatten"):
            found.extend(text_fields(document, document["structs"][field["struct"]]))
        elif field["kind"] == "text":
            found.append((field["name"], field))
    return found


def child_types(document: dict[str, Any], body: dict[str, Any]) -> dict[str, str]:
    """Nested object type per public property, following flattened structs.

    A flattened struct contributes its properties at this level, so its children
    have to be reported here too or a validator walking the document would stop
    at the boundary and miss everything below it.
    """
    children: dict[str, str] = {}
    for field in serialized_fields(body):
        if field.get("flatten"):
            children.update(child_types(document, document["structs"][field["struct"]]))
        elif field["kind"] == "struct":
            children[json_key(field)] = field["struct"]
        elif field["kind"] == "array" and not field.get("json_variants"):
            children[json_key(field)] = field["struct"]
        elif field["kind"] == "external" and not field.get("inline"):
            children[json_key(field)] = field["external"]
    return children


def widget_variants(document: dict[str, Any]) -> dict[str, str]:
    """Widget discriminator value to the struct that carries its properties."""
    return {
        body["widget_type"]: name
        for name, body in document["structs"].items()
        if body.get("widget_type")
    }


def widget_pools(document: dict[str, Any]) -> list[tuple[str, str, dict[str, Any]]]:
    """(discriminator, struct, storage array), in WidgetType order.

    The traits table is indexed by the enum, so the order has to be the enum's.
    Storage names are read from the schema rather than derived from the struct
    name, so renaming a pool cannot silently produce a table that compiles
    against the wrong array.
    """
    variants = widget_variants(document)
    declared = set(document["enums"]["WidgetType"]["json_values"])
    if set(variants) != declared:
        fail(
            "WidgetType values and widget_type structs disagree: "
            f"{sorted(declared ^ set(variants))}"
        )
    arrays = {
        field["struct"]: field
        for field in document["structs"]["DashboardConfiguration"]["fields"]
        if field["kind"] == "array"
    }
    pools: list[tuple[str, str, dict[str, Any]]] = []
    for value in document["enums"]["WidgetType"]["json_values"]:
        struct = variants[value]
        if struct not in arrays:
            fail(f"{struct} has no storage array in DashboardConfiguration")
        pools.append((value, struct, arrays[struct]))
    return pools


